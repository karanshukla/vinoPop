"""Per-file sha256 checks for the downloaded LLMs.

Modelled on vinoWhisper's integrity.py, but simpler: vinoPop downloads
pre-converted exports at a pinned Hugging Face commit, and the bytes a
commit serves can't change. So drift and tampering are told apart by the
revision, not by the export toolchain:

- the folder was downloaded at a different commit than the one pinned now
  (DRIFT): an older download, replaced on next use. Not a security problem.
- same commit, different bytes (MISMATCH): the download is corrupt or was
  altered on disk or in transit. Never an upstream update.

model_digests.json is generated by scripts/update_digests.py from the
Hugging Face API and is meant to be read in review. Hashing a 4 GB model
takes a while, so this runs after a download and in `vinopop --doctor`,
never on every start.
"""

from __future__ import annotations

import hashlib
import json
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

DIGESTS_PATH = Path(__file__).resolve().parent / "model_digests.json"
SCHEMA = 1

VERIFIED = "verified"
UNPINNED = "unpinned"
DRIFT = "drift"
MISMATCH = "mismatch"
INCOMPLETE = "incomplete"

SEVERE = (MISMATCH, INCOMPLETE)

_CHUNK = 1 << 20
# Files that aren't part of the snapshot: huggingface_hub's own metadata
# and vinoPop's markers (see models.py).
_IGNORED_PREFIXES = (".cache/", ".vinopop-", ".complete")


@dataclass(frozen=True)
class FileDigest:
    sha256: str
    size: int


Digests = dict[str, dict[str, dict[str, FileDigest]]]  # repo -> revision -> file


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(_CHUNK):
            digest.update(chunk)
    return digest.hexdigest()


def load(path: Path | None = None) -> Digests:
    """The digest table, or {} when it's missing or unreadable (then every
    model reads as unpinned, which is reported, not fatal)."""
    try:
        raw = json.loads((path or DIGESTS_PATH).read_text(encoding="utf-8"))
        models = raw["models"]
        return {
            repo: {
                revision: {
                    name: FileDigest(str(meta["sha256"]), int(meta["size"]))
                    for name, meta in entry["files"].items()
                }
                for revision, entry in revisions.items()
            }
            for repo, revisions in models.items()
        }
    except (OSError, ValueError, KeyError, TypeError, AttributeError):
        return {}


def expected(repo: str, revision: str, table: Digests | None = None) -> dict[str, FileDigest]:
    """{file: digest} pinned for repo at revision; empty when there's no pin."""
    return (load() if table is None else table).get(repo, {}).get(revision, {})


def _local_files(directory: Path) -> list[str]:
    names = []
    for path in directory.rglob("*"):
        rel = path.relative_to(directory).as_posix()
        if path.is_file() and not rel.startswith(_IGNORED_PREFIXES):
            names.append(rel)
    return sorted(names)


@dataclass(frozen=True)
class Verification:
    status: str
    repo: str
    directory: Path
    revision: str  # the commit the folder was downloaded at
    pinned_revision: str = ""
    matched: tuple[str, ...] = ()
    differing: tuple[str, ...] = ()
    missing: tuple[str, ...] = ()
    extra: tuple[str, ...] = ()

    @property
    def severe(self) -> bool:
        return self.status in SEVERE

    def summary(self) -> str:
        if self.status == VERIFIED:
            return f"{len(self.matched)} files match their pinned sha256"
        if self.status == UNPINNED:
            return f"no pinned digests for {self.repo}@{self.revision[:12]}, files not checked"
        if self.status == DRIFT:
            return (
                f"downloaded at {self.revision[:12] or 'an unknown commit'}, the pin is now "
                f"{self.pinned_revision[:12]}: an older download, replaced on next use"
            )
        if self.status == INCOMPLETE:
            return f"{len(self.missing)} pinned file(s) missing: {', '.join(self.missing[:3])}"
        return (
            f"{len(self.differing)} file(s) differ from the pinned sha256 at the same commit, "
            f"so the download is corrupt or was altered: {', '.join(self.differing[:3])}"
        )


def verify(
    directory: Path,
    repo: str,
    revision: str,
    pinned_revision: str = "",
    table: Digests | None = None,
    on_file: Callable[[str], None] | None = None,
) -> Verification:
    """Check `directory`, downloaded from `repo` at `revision`, against the
    pinned digests. A revision other than `pinned_revision` is DRIFT and
    isn't hashed. A file whose size is already wrong isn't hashed either."""
    if pinned_revision and revision != pinned_revision:
        return Verification(DRIFT, repo, directory, revision, pinned_revision)
    pins = expected(repo, revision, table)
    if not pins:
        return Verification(UNPINNED, repo, directory, revision, pinned_revision)

    matched, differing, missing = [], [], []
    for name, pin in sorted(pins.items()):
        path = directory / name
        if not path.is_file():
            missing.append(name)
            continue
        if on_file:
            on_file(name)
        if path.stat().st_size == pin.size and sha256_file(path) == pin.sha256:
            matched.append(name)
        else:
            differing.append(name)
    extra = [n for n in _local_files(directory) if n not in pins]
    status = INCOMPLETE if missing else MISMATCH if differing else VERIFIED
    return Verification(
        status,
        repo,
        directory,
        revision,
        pinned_revision,
        matched=tuple(matched),
        differing=tuple(differing),
        missing=tuple(missing),
        extra=tuple(extra),
    )
